// Operators are signs or symbols used to perform operations.

// Addition operator (+) is used to add two values.
// Subtraction operator (-) is used to subtract two values.
// Multiplication operator (*) is used to multiply two values.
// Division operator (/) is used to divide two values.

// Declare the first number.
var num1 = 60;

// Declare the second number.
var num2 = 20;

// Add num1 and num2.
console.log(num1 + num2); // 80

// Multiply num1 and num2.
console.log(num1 * num2); // 1200

// Divide num1 by num2.
console.log(num1 / num2); // 3


// Increment operator (++) increases the value by 1.

// Declare the age variable.
var age = 15;

// Increase the value of age by 1.
age++;

// Print the updated value of age.
console.log(age); // 16


// Decrement operator (--) decreases the value by 1.

// Decrease the value of age by 1.
age--;

// Print the updated value of age.
console.log(age); // 15

// Print a separator.
console.log("--------------------");


// Post-increment means the current value is used first,
// and then the value is increased by 1.

// Declare the variable a.
var a = 10;

// Print the current value first and then increment a.
console.log(a++); // 10

// Print the updated value of a.
console.log(a); // 11


// Pre-increment means the value is increased first,
// and then the updated value is used.

// Increment a by 1 first and then print the value.
console.log(++a); // 12


// Post-decrement means the current value is used first,
// and then the value is decreased by 1.

// Print the current value first and then decrement a.
console.log(a--); // 12

// Print the updated value of a.
console.log(a); // 11


// Pre-decrement means the value is decreased first,
// and then the updated value is used.

// Decrement a by 1 first and then print the value.
console.log(--a); // 10


// Comparison Operators are used to compare values.

// =   → Assignment operator
// ==  → Compares values after type conversion
// === → Compares both value and data type


// Assign the value 1 to b.
var b = 1;

// Assign the string value "Vineeth" to c.
var c = "Vineeth";

// Compare the value and data type of c with "Vineeth".
console.log(c === "Vineeth"); // true