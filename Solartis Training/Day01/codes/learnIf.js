// Declare a variable with the value 0.
var d = 0;

// Check whether d is greater than 0.
if (d > 0) {

    // Print the message when d is positive.
    console.log("The number is positive");
}

// Check whether d is less than 0.
else if (d < 0) {

    // Print the message when d is negative.
    console.log("The number is negative");
}

// Execute this block when neither of the above conditions is true.
else {

    // Print the message when d is zero.
    console.log("The number is zero");
}