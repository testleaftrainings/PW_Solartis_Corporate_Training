// Define a function named login with two string parameters.
function login(username: string, password: string) {

    // Print the username received through the parameter.
    console.log(username);

    // Print the password received through the parameter.
    console.log(password);
}

// Call the login function with "Demo1" as username and "Pass1" as password.
login("Demo1", "Pass1");

// Call the login function with "Demo2" as username and "pass2" as password.
login("Demo2", "pass2");